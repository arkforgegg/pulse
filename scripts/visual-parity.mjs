// Visual parity: screenshots the ORIGINAL v18 build and the NEW build side by side and diffs them.
//   ORIGINAL_URL=http://127.0.0.1:8787 NEW_URL=http://localhost:4173 npm run parity
// Writes PNGs, diff images and REPORT.md to docs/visual-parity/. Exit code 1 if any shot differs
// by more than MAX_DIFF_RATIO.
import { mkdirSync, writeFileSync } from "node:fs";
import pixelmatch from "pixelmatch";
import { chromium } from "playwright";
import { PNG } from "pngjs";

const ORIGINAL_URL = process.env.ORIGINAL_URL ?? "http://127.0.0.1:8787/";
const NEW_URL = process.env.NEW_URL ?? "http://localhost:4173/";
const OUT = new URL("../docs/visual-parity/", import.meta.url);
const MAX_DIFF_RATIO = Number(process.env.MAX_DIFF_RATIO ?? 0.001);
const VIEWPORTS = { mobile: { width: 390, height: 844 }, desktop: { width: 1440, height: 900 } };
const DIRECTIONS = ["Entering China", "Going global", "Both directions"];

async function settle(page) {
  // Walk the page so lazy images load, then wait for fonts and images before returning to the top.
  const height = await page.evaluate(() => document.documentElement.scrollHeight);
  for (let y = 0; y < height; y += 600) await page.evaluate((top) => window.scrollTo({ top, behavior: "instant" }), y);
  await page.evaluate(async () => {
    await document.fonts.ready;
    await Promise.all([...document.images].map((img) => (img.complete ? null : new Promise((r) => { img.onload = img.onerror = r; }))));
  });
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
  await page.waitForTimeout(300);
}

async function capture(browser, url, viewport) {
  const page = await browser.newPage({ viewport, deviceScaleFactor: 1 });
  await page.goto(url, { waitUntil: "load" });
  await settle(page);
  const shots = { page: await page.screenshot({ fullPage: true, animations: "disabled" }) };
  await page.locator(".intakeDisclosure > summary").click();
  for (const direction of DIRECTIONS) {
    await page.locator('select[name="consultationDirection"]').selectOption(direction);
    await page.locator('select[name="consultationDirection"]').blur();
    await settle(page);
    shots[`form-${direction.toLowerCase().replace(/ /g, "-")}`] = await page.locator(".intakeDisclosure").screenshot({ animations: "disabled" });
  }
  await page.close();
  return shots;
}

function pad(png, width, height) {
  if (png.width === width && png.height === height) return png;
  const out = new PNG({ width, height });
  out.data.fill(0xff);
  PNG.bitblt(png, out, 0, 0, png.width, png.height, 0, 0);
  return out;
}

function diff(originalBuffer, newBuffer) {
  const a = PNG.sync.read(originalBuffer);
  const b = PNG.sync.read(newBuffer);
  const width = Math.max(a.width, b.width);
  const height = Math.max(a.height, b.height);
  const out = new PNG({ width, height });
  const pixels = pixelmatch(pad(a, width, height).data, pad(b, width, height).data, out.data, width, height, { threshold: 0.1 });
  return { pixels, ratio: pixels / (width * height), sameSize: a.width === b.width && a.height === b.height, sizes: [`${a.width}×${a.height}`, `${b.width}×${b.height}`], png: PNG.sync.write(out) };
}

mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
const rows = [];
let failed = false;
for (const [label, viewport] of Object.entries(VIEWPORTS)) {
  const original = await capture(browser, ORIGINAL_URL, viewport);
  const updated = await capture(browser, NEW_URL, viewport);
  for (const shot of Object.keys(original)) {
    const name = `${label}-${shot}`;
    const result = diff(original[shot], updated[shot]);
    writeFileSync(new URL(`${name}-original.png`, OUT), original[shot]);
    writeFileSync(new URL(`${name}-new.png`, OUT), updated[shot]);
    writeFileSync(new URL(`${name}-diff.png`, OUT), result.png);
    const pass = result.sameSize && result.ratio <= MAX_DIFF_RATIO;
    failed ||= !pass;
    rows.push(`| ${name} | ${result.sizes[0]} | ${result.sizes[1]} | ${result.pixels} | ${(result.ratio * 100).toFixed(4)}% | ${pass ? "✅" : "❌"} |`);
    console.log(`${pass ? "PASS" : "FAIL"} ${name}: ${result.pixels} px (${(result.ratio * 100).toFixed(4)}%) ${result.sizes.join(" vs ")}`);
  }
}
await browser.close();

writeFileSync(new URL("REPORT.md", OUT), `# Visual parity — v18 (ChatGPT Sites) vs GitHub Pages build

Generated by \`npm run parity\` on ${new Date().toISOString()}.
Original: ${ORIGINAL_URL} (v18 vinext production build) · New: ${NEW_URL} (\`vite preview\` of this repo).
Chromium (Playwright ${(await import("playwright/package.json", { with: { type: "json" } })).default.version}), deviceScaleFactor 1, pixelmatch threshold 0.1.
Pass = identical dimensions and ≤ ${(MAX_DIFF_RATIO * 100).toFixed(2)}% differing pixels.

| Shot | Original | New | Differing px | Ratio | Result |
|---|---|---|---:|---:|:---:|
${rows.join("\n")}

Each shot has \`*-original.png\`, \`*-new.png\` and \`*-diff.png\` (differing pixels in red) in this folder.
"form-*" shots are the opened "Book your free consultation" panel with that consultation direction selected.
`);
process.exit(failed ? 1 : 0);
